# Live readiness directory for the Fit / Unfit Soldiers roster.
# Every score is generated by the existing Fusion Engine from database records.
@app.get("/readiness-directory")
def get_readiness_directory(db: Session = Depends(get_db)):
    soldiers = db.execute(text("""
        SELECT Soldier_ID, Soldier_Name, `Rank`, Gender, Age
        FROM soldiers
        ORDER BY Soldier_ID
    """)).mappings().all()

    def fetch_table(table_name):
        rows = db.execute(text(f"SELECT * FROM `{table_name}`")).mappings().all()
        return {row["Soldier_ID"]: dict(row) for row in rows}

    physical_rows = fetch_table("physical_fitness")
    health_rows = fetch_table("health_recovery")
    injury_rows = fetch_table("injury_records")

    models = get_models()
    physical_features = list(models["model_1"].feature_names_in_)
    health_features = list(models["model_2_metadata"]["features"])
    injury_features = list(models["model_3"].feature_names_in_)

    roster = []
    summary = {
        "combat_ready": 0,
        "conditionally_ready": 0,
        "not_combat_ready": 0,
        "assessment_unavailable": 0
    }

    for soldier in soldiers:
        soldier_id = soldier["Soldier_ID"]
        physical = physical_rows.get(soldier_id)
        health = health_rows.get(soldier_id)
        injury = injury_rows.get(soldier_id)

        row = {
            "soldier_id": soldier_id,
            "name": soldier["Soldier_Name"],
            "rank": soldier["Rank"],
            "unit": None,
            "age": soldier["Age"],
            "gender": soldier["Gender"],
            "assessment_date": physical.get("Assessment_Date") if physical else None,
            "readiness_score": None,
            "readiness_status": "Assessment Unavailable",
            "physical_fitness_score": None,
            "injury_probability": None,
            "injury_prediction": None,
            "assessment_available": False,
            "physical_fitness": physical,
            "health_recovery": health,
            "injury_risk": injury
        }

        try:
            if physical is None or health is None or injury is None:
                raise ValueError("One or more required assessment records are missing.")

            physical_data = {feature: physical[feature] for feature in physical_features}
            health_data = {feature: health[feature] for feature in health_features}
            injury_data = {feature: injury[feature] for feature in injury_features}

            fusion = run_fusion_engine(
                physical_data=physical_data,
                health_data=health_data,
                injury_data=injury_data
            )

            if fusion.get("readiness_score") is None:
                raise ValueError(fusion.get("readiness_error") or "Fusion assessment unavailable.")

            row["readiness_score"] = fusion["readiness_score"]
            row["readiness_status"] = fusion["readiness_status"]
            row["physical_fitness_score"] = fusion["predictions"]["physical_fitness"]["data"].get("predicted_fitness_score")
            row["injury_probability"] = fusion["predictions"]["injury_risk"]["data"].get("injury_probability")
            row["injury_prediction"] = fusion["predictions"]["injury_risk"]["data"].get("predicted_injury")
            row["assessment_available"] = True
            row["fusion"] = fusion

            status = fusion["readiness_status"]
            if status == "Combat Ready":
                summary["combat_ready"] += 1
            elif status == "Conditionally Ready":
                summary["conditionally_ready"] += 1
            else:
                summary["not_combat_ready"] += 1

        except Exception as error:
            row["assessment_error"] = str(error)
            summary["assessment_unavailable"] += 1

        roster.append(row)

    return {
        "project": "S.A.R.T.H.I.",
        "total_soldiers": len(roster),
        "summary": summary,
        "soldiers": roster
    }


