@app.post("/predict/soldier/{soldier_id}")
def predict_soldier_from_database(
    soldier_id: str,
    db: Session = Depends(get_db)
):
    soldier_query = text("""
        SELECT Soldier_ID
        FROM soldiers
        WHERE Soldier_ID = :soldier_id
    """)

    soldier = db.execute(
        soldier_query,
        {"soldier_id": soldier_id}
    ).first()

    if soldier is None:
        raise HTTPException(
            status_code=404,
            detail=f"Soldier ID '{soldier_id}' not found"
        )
    tables = [
        "physical_fitness",
        "health_recovery",
        "injury_records"
    ]

    records = {}

    for table in tables:
        query = text(f"""
            SELECT *
            FROM `{table}`
            WHERE Soldier_ID = :soldier_id
        """)

        record = db.execute(
            query,
            {"soldier_id": soldier_id}
        ).mappings().first()

        if record is None:
            raise HTTPException(
                status_code=404,
                detail=f"Record missing in {table}"
            )

        records[table] = dict(record)

    # Load model feature requirements
    models = get_models()

    physical_features = list(
        models["model_1"].feature_names_in_
    )

    health_features = models["model_2_metadata"]["features"]

    injury_features = list(
        models["model_3"].feature_names_in_
    )

    # Keep only the features required by each model
    physical_data = {
        feature: records["physical_fitness"][feature]
        for feature in physical_features
    }

    health_data = {
        feature: records["health_recovery"][feature]
        for feature in health_features
    }

    injury_data = {
        feature: records["injury_records"][feature]
        for feature in injury_features
    }

    # Run all models through the fusion engine
    result = run_fusion_engine(
        physical_data=physical_data,
        health_data=health_data,
        injury_data=injury_data
    )

    try:
        save_prediction_history(
            db=db,
            soldier_id=soldier_id,
            prediction_result=result
        )

    except SQLAlchemyError:
        db.rollback()

        raise HTTPException(
            status_code=500,
            detail="Prediction generated, but history could not be saved"
        )

    return {
        "soldier_id": soldier_id,
        "prediction_result": result
    }





# Prediction History API
@app.get("/prediction-history/{soldier_id}")
def get_prediction_history(
    soldier_id: str,
    db: Session = Depends(get_db)
):
    # Verify soldier exists
    soldier = db.execute(
        text("""
            SELECT Soldier_ID
            FROM soldiers
            WHERE Soldier_ID = :soldier_id
        """),
        {"soldier_id": soldier_id}
    ).fetchone()

    if not soldier:
        raise HTTPException(
            status_code=404,
            detail="Soldier not found"
        )

    query = text("""
        SELECT
            Prediction_ID,
            Soldier_ID,
            Model_1_Prediction,
            Model_2_Prediction,
            Model_3_Prediction,
            Prediction_Timestamp
        FROM prediction_history
        WHERE Soldier_ID = :soldier_id
        ORDER BY Prediction_Timestamp DESC
    """)

    result = db.execute(
        query,
        {"soldier_id": soldier_id}
    ).mappings().all()

    return {
        "soldier_id": soldier_id,
        "total_predictions": len(result),
        "history": [dict(row) for row in result]
    }






# Unified Dashboard API
@app.get("/dashboard/{soldier_id}")
def get_soldier_dashboard(
    soldier_id: str,
    db: Session = Depends(get_db)
):
    # 1. Verify Soldier
    soldier_query = text("""
        SELECT
            Soldier_ID,
            Soldier_Name,
            `Rank`,
            Gender,
            Age
        FROM soldiers
        WHERE Soldier_ID = :soldier_id
    """)

    soldier = db.execute(
        soldier_query,
        {"soldier_id": soldier_id}
    ).mappings().first()

    if soldier is None:
        raise HTTPException(
            status_code=404,
            detail=f"Soldier ID '{soldier_id}' not found"
        )

    # 2. Fetch Complete Records
    tables = [
        "physical_fitness",
        "health_recovery",
        "injury_records"
    ]

    records = {}

    for table in tables:
        query = text(f"""
            SELECT *
            FROM `{table}`
            WHERE Soldier_ID = :soldier_id
        """)

        record = db.execute(
            query,
            {"soldier_id": soldier_id}
        ).mappings().first()

        records[table] = dict(record) if record else None






    # Run Fusion Engine for current dashboard assessment
    dashboard_fusion = None
    dashboard_fusion_error = None

    try:
        required_tables = [
            "physical_fitness",
            "health_recovery",
            "injury_records"
        ]

        if any(records.get(table) is None for table in required_tables):
            raise ValueError("Required soldier assessment records are missing.")

        models = get_models()

        physical_features = list(
            models["model_1"].feature_names_in_
        )

        health_features = models["model_2_metadata"]["features"]

        injury_features = list(
            models["model_3"].feature_names_in_
        )

        physical_data = {
            feature: records["physical_fitness"][feature]
            for feature in physical_features
        }

        health_data = {
            feature: records["health_recovery"][feature]
            for feature in health_features
        }

        injury_data = {
            feature: records["injury_records"][feature]
            for feature in injury_features
        }

        dashboard_fusion = run_fusion_engine(
            physical_data=physical_data,
            health_data=health_data,
            injury_data=injury_data
        )

    except Exception as error:
        dashboard_fusion_error = str(error)






# Separate historical injury outcome from risk factors
    injury_record = records.get("injury_records")

    historical_injury_outcome = None

    if injury_record is not None:

        outcome_fields = [
            "Injury_Occurred",
            "Injury_Type",
            "Injury_Body_Part",
            "Injury_Severity"
        ]

        historical_injury_outcome = {}

        for field in outcome_fields:
            if field in injury_record:
                historical_injury_outcome[field] = injury_record.pop(field)

        if not historical_injury_outcome:
            historical_injury_outcome = None




    # 3. Fetch Prediction History
    history_query = text("""
        SELECT
            Prediction_ID,
            Model_1_Prediction,
            Model_2_Prediction,
            Model_3_Prediction,
            Prediction_Timestamp
        FROM prediction_history
        WHERE Soldier_ID = :soldier_id
        ORDER BY Prediction_Timestamp DESC
    """)

    history = db.execute(
        history_query,
        {"soldier_id": soldier_id}
    ).mappings().all()

    history = [dict(row) for row in history]

    # 4. Get Latest Prediction
    latest_prediction = history[0] if history else None


    # 5. Identify Potential Problem Areas
    problem_areas = []

    # Get latest live Fusion Engine predictions
    fusion_predictions = (
        dashboard_fusion.get("predictions", {})
        if dashboard_fusion
        else {}
    )

    # ---------------------------------
    # A. Injury Risk Indicator
    # ---------------------------------
    injury_result = fusion_predictions.get("injury_risk", {})

    if injury_result.get("status") == "success":
        injury_data = injury_result.get("data", {})

        injury_prediction = injury_data.get("predicted_injury")
        injury_probability = injury_data.get("injury_probability")

        if (
            str(injury_prediction).strip().lower() == "yes"
            or (
                injury_probability is not None
                and float(injury_probability) >= 50
            )
        ):
            problem_areas.append({
                "area": "Injury Risk",
                "message": "The injury risk model has flagged an elevated risk indicator.",
                "status": "Attention Required",
                "note": "Research model prediction only - not a medical diagnosis."
            })

    # ---------------------------------
    # B. Physical Fitness Indicator
    # ---------------------------------
    physical_result = fusion_predictions.get(
        "physical_fitness", {}
    )

    if physical_result.get("status") == "success":
        fitness_score = physical_result.get(
            "data", {}
        ).get("predicted_fitness_score")

        if fitness_score is not None and float(fitness_score) < 50:
            problem_areas.append({
                "area": "Physical Fitness",
                "message": "Predicted physical fitness score is below 50.",
                "status": "Needs Improvement",
                "note": "Academic demonstration threshold."
            })

    # ---------------------------------
    # C. Health and Recovery Indicators
    # ---------------------------------
    health_record = records.get("health_recovery") or {}

    stress_level = health_record.get("Stress Level")

    sleep_quality = health_record.get(
        "Quality of Sleep",
        health_record.get("Sleep Quality")
    )

    # Demo threshold: Stress Level >= 7
    if stress_level is not None and float(stress_level) >= 7:
        problem_areas.append({
            "area": "Stress Level",
            "message": "Stress level has reached the project monitoring threshold.",
            "status": "Monitor",
            "note": "Research demonstration threshold - not a clinical assessment."
        })

    # Demo threshold: Sleep Quality <= 6
    if sleep_quality is not None and float(sleep_quality) <= 6:
        problem_areas.append({
            "area": "Sleep Quality",
            "message": "Sleep quality is at or below the project monitoring threshold.",
            "status": "Monitor",
            "note": "Research demonstration threshold - not a clinical assessment."
        })



# 6. Final Dashboard Response
    return {
        "project": "S.A.R.T.H.I.",
        "soldier": dict(soldier),

        "health_and_fitness": records,

        "historical_injury_outcome": {
            "source": "Dataset Historical Outcome",
            "data": historical_injury_outcome
        },

        "latest_prediction": latest_prediction,

        "prediction_history": {
            "total_predictions": len(history),
            "history": history
        },

        "problem_areas": problem_areas,

        "readiness": {
            "score": (
                dashboard_fusion["readiness_score"]
                if dashboard_fusion
                else None
            ),
            "status": (
                dashboard_fusion["readiness_status"]
                if dashboard_fusion
                else "Not Available"
            ),
            "score_status": (
                dashboard_fusion["readiness_score_status"]
                if dashboard_fusion
                else "Unavailable"
            ),
            "details": (
                dashboard_fusion["readiness_details"]
                if dashboard_fusion
                else None
            ),
            "error": dashboard_fusion_error
        }
    }


