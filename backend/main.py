# Fusion API Request Structure
class FusionRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    physical_data: dict[str, Any]
    health_data: dict[str, Any]
    injury_data: dict[str, Any]

    @field_validator(
        "physical_data",
        "health_data",
        "injury_data",
        mode="before"
    )
    @classmethod
    def validate_data_sections(cls, value):
        if not isinstance(value, dict):
            raise ValueError("Each data section must be a dictionary")

        for key in value:
            if not isinstance(key, str) or not key.strip():
                raise ValueError("Feature names must be non-empty strings")

        return value



def save_prediction_history(
    db: Session,
    soldier_id: str,
    prediction_result: dict
):
    predictions = prediction_result.get("predictions", {})

    physical_result = predictions.get(
        "physical_fitness", {}
    )

    health_result = predictions.get(
        "health_recovery", {}
    )

    injury_result = predictions.get(
        "injury_risk", {}
    )

    physical_score = None
    health_score = None
    injury_prediction = None

    if physical_result.get("status") == "success":
        physical_score = physical_result["data"].get(
            "predicted_fitness_score"
        )

    if health_result.get("status") == "success":
        health_score = health_result["data"].get(
            "predicted_fitness_score"
        )

    if injury_result.get("status") == "success":
        injury_prediction = injury_result["data"].get(
            "predicted_injury"
        )

    query = text("""
        INSERT INTO prediction_history (
            Soldier_ID,
            Model_1_Prediction,
            Model_2_Prediction,
            Model_3_Prediction
        )
        VALUES (
            :soldier_id,
            :model_1,
            :model_2,
            :model_3
        )
    """)

    db.execute(
        query,
        {
            "soldier_id": soldier_id,
            "model_1": physical_score,
            "model_2": health_score,
            "model_3": injury_prediction
        }
    )

    db.commit()


